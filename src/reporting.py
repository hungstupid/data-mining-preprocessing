_TABLE_HEAD = re.compile(r"<thead\b[^>]*>.*?</thead>", re.DOTALL)
_HEADER_CELL = re.compile(r"(<th\b[^>]*>)([^<]*)(</th>)")
_SCROLL_REGION = re.compile(r"""(<div )(?=style=["']overflow)""")


def _localize_headers(head):
    def rename(cell):
        label = unescape(cell[2]).strip().casefold()
        translation = COLUMN_LABELS.get(label)
        return cell[0] if translation is None else cell[1] + escape(translation) + cell[3]

    return _HEADER_CELL.sub(rename, head[0])


def display_report(value):
    """Đổi nhãn hiển thị của bảng kết quả, giữ nguyên các giá trị để tính toán."""
    data, metadata = get_ipython().display_formatter.format(value)
    if "text/html" in data:
        html = _TABLE_HEAD.sub(_localize_headers, data["text/html"])
        data["text/html"] = _SCROLL_REGION.sub(r'\1tabindex="0" ', html)
    display(data, metadata=metadata, raw=True)


def show_figure(fig, description):
    """Xuất PNG thật với mô tả dùng làm văn bản thay thế khi build MyST."""
    png = print_figure(fig, fmt="png", bbox_inches="tight")
    display({"image/png": base64.b64encode(png).decode("ascii"), "text/plain": description}, raw=True)
    display(Markdown(f"*{description}*"))
    plt.close(fig)
